#!/usr/bin/env python3
"""Specialize NB2 settlement and proofs while retaining the pinned native sources."""

import argparse
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[2] / "src/nb2"
FLAT = ROOT / "verifier/flat"
OUT = ROOT / "erc20/generated"
HEADER = "// Generated by script/nb2-erc20/generate.py from {name}.\n"
FLAT_CONFIG = 'import {ERC20FlatConfig as FlatConfig} from "../ERC20FlatConfig.sol";\n'


def replace(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f"expected exactly one instance of {old!r}")
    return source.replace(old, new)


def between(source, start, end, value=""):
    i = source.index(start)
    j = source.index(end, i + len(start))
    return source[:i] + value + source[j:]


def variant_imports(source):
    for name in ("FlatNative", "FlatPacket", "FlatReceipts", "FlatSparse", "FlatTypes"):
        source = source.replace(f'"./{name}.sol"', f'"../../verifier/flat/{name}.sol"')
    for name in ("Nb2Cbor", "Nb2Crypto"):
        source = source.replace(f'"../{name}.sol"', f'"../../verifier/{name}.sol"')
    return replace(source, "import {\n    FlatConfig,\n", FLAT_CONFIG + "import {\n")


def base(source):
    source = replace(source, 'import {NB2Gap} from "./NB2Gap.sol";',
                     'import {NB2Gap} from "../../NB2Gap.sol";\n'
                     'import {ERC20Config} from "../ERC20Config.sol";')
    source = replace(source, '"./NB2Config.sol"', '"../../NB2Config.sol"')
    source = replace(source, "abstract contract NB2VaultBase", "abstract contract ERC20VaultBase")
    source = between(source, "    bytes32 internal constant ASSET_UCT", "    bytes32 internal constant TOPIC_PAID",
                     "    address public immutable TOKEN;\n    bytes32 public immutable ASSET;\n")
    source = replace(source, "    bytes32 internal immutable G11;",
                     "    bytes32 internal immutable G11;\n    bytes32 internal immutable G12;\n"
                     "    bytes32 internal immutable G13;\n    bytes32 internal immutable G14;")
    source = between(source, "    /// @param kSet", "        uint256 logk",
                     """    constructor(bytes memory gamma) {
        ERC20Config.Config memory full = ERC20Config.decode(gamma);
        ERC20Config.checkEnvironment(full, address(this));
        NB2Config.Config memory c = full.base;
        TOKEN = full.token;
        ASSET = c.asset;
""")
    source = replace(source, "        // A decoded Γ is at most 378 bytes: twelve words hold it (config()).",
                     "        // The ERC20 decoder bounds Γ to fifteen words (config()).")
    source = replace(source, "        bytes32[12] memory w;", "        bytes32[15] memory w;")
    source = replace(source, "        G11 = w[11];", "        G11 = w[11];\n"
                     "        G12 = w[12];\n        G13 = w[13];\n        G14 = w[14];")
    words = "bytes32[12] memory w = [G0, G1, G2, G3, G4, G5, G6, G7, G8, G9, G10, G11];"
    if source.count(words) != 2:
        raise ValueError("expected both config readers")
    source = source.replace(words, "bytes32[15] memory w = [\n"
                            "            G0, G1, G2, G3, G4, G5, G6, G7, G8, G9, G10, G11, G12, G13, G14\n"
                            "        ];")
    source = between(source, "    // -------------------------------------------------------------------------------------------- deposit",
                     "    // -------------------------------------------------------------------------------------------- redeem")
    source = replace(source, "if (vasset != ASSET_UCT)", "if (vasset != ASSET)")
    source = between(source, "    function _pay", "    // -------------------------------------------------------------------------------------------- sealing",
                     "    function _pay(address recipient, uint256 amount) internal virtual;\n\n")
    source = between(source, "/// @notice", "abstract contract ERC20VaultBase",
                     "/// @notice ERC20 specialization of the native NB2 bounded settlement core.\n")
    return source


def recovered(source):
    source = source.replace('"./NB2Config.sol"', '"../../NB2Config.sol"').replace(
        '"./NB2Gap.sol"', '"../../NB2Gap.sol"').replace('"./verifier/flat/', '"../../verifier/flat/')
    source = replace(source, 'import {NB2VaultBase} from "./NB2VaultBase.sol";',
                     'import {ERC20VaultBase} from "./ERC20VaultBase.sol";\n'
                     'import {ERC20Config} from "../ERC20Config.sol";')
    source = replace(source, "abstract contract NB2VaultRecovered is NB2VaultBase",
                     "abstract contract ERC20VaultRecovered is ERC20VaultBase")
    source = replace(source, "        uint256 kSet,\n        uint256 bSet,\n", "")
    source = replace(source, ") NB2VaultBase(gamma, kSet, bSet, 2) {\n"
                     "        NB2Config.Config memory c = NB2Config.decode(gamma, kSet, bSet, 2);",
                     ") ERC20VaultBase(gamma) {\n"
                     "        ERC20Config.Config memory full = ERC20Config.decode(gamma);\n"
                     "        NB2Config.Config memory c = full.base;")
    source = replace(source, "_bindRecovery(recovery, recoveryRuntime, c);",
                     "_bindRecovery(recovery, recoveryRuntime, c);\n"
                     "        if (pins != full.pins || generation != FlatBindings.generation(full.generation, D)) {\n"
                     "            revert NB2Config.BadConfig(21);\n        }")
    return source


def bindings(source):
    source = source[source.index("    struct ConfigBinding"):]
    source = """// SPDX-License-Identifier: MIT
pragma solidity 0.8.37;

// The CBOR reader bounds each field before narrowing.
// forge-lint: disable-start(unsafe-typecast)
import {Nb2Cbor as C} from "../../verifier/Nb2Cbor.sol";
import {FlatWire as W, BadBinding} from "../../verifier/flat/FlatTypes.sol";
import {ERC20Config} from "../ERC20Config.sol";
""" + FLAT_CONFIG + "\nlibrary ERC20FlatBindings {\n" + source
    source = replace(source, "p = C.array(p, 19);", "p = C.array(p, 22);")
    source = replace(source, "p = C.version(next, 2);", "p = C.version(next, 3);")
    source = replace(source, "        bytes32 rootGenesis;\n", "")
    source = replace(source, "(rootGenesis, p) = C.bytes32At(p);", "(, p) = C.bytes32At(p);")
    source = replace(source, "        bytes32 asset;\n        (asset, p) =", "        (b.cfg.asset, p) =")
    return between(source, "        (v, p) = C.amount(p);", "        b.cfg.domain = sha256(gamma);",
                   """        (v, p) = C.amount(p);
        (b.cfg.token, p) = _address(p);
        (bytes32 generation, uint256 afterGeneration) = C.bytes32At(p);
        (bytes32 pins, uint256 end) = C.bytes32At(afterGeneration);
        if (
            end != W.offset(gamma) + gamma.length || v >= 1 << 144
                || b.cfg.vault == address(0) || b.ordinary == address(0)
                || b.cfg.token == address(0) || generation == 0 || pins == 0
        ) revert BadBinding();
        (bytes32 asset, bytes32 coin, bytes32 tokenType) =
            ERC20Config.identities(b.chainId, b.cfg.token, executionGenesis);
        if (b.cfg.asset != asset || b.cfg.coin != coin || b.cfg.tokenType != tokenType) {
            revert BadBinding();
        }
""")


def lineage(source):
    source = variant_imports(source)
    source = replace(source, "    FlatHash,\n", "")
    source = replace(source, "contract FlatLineage", "contract ERC20FlatLineage")
    source = replace(source, '"Deposited(uint64,bytes32,uint256,bytes32,bytes)"',
                     '"ERC20Deposited(uint64,address,bytes32,uint256,bytes32,bytes)"')
    source = replace(source, "topics.length != 2 || topics[0] != DEPOSITED || uint256(topics[1]) != nonce",
                     "topics.length != 3 || topics[0] != DEPOSITED || uint256(topics[1]) != nonce\n"
                     "                || uint256(topics[2]) != uint256(uint160(cfg.token))")
    return replace(source, "v.asset != FlatHash.ASSET", "v.asset != cfg.asset")


def ordinary(source):
    source = variant_imports(source)
    source = replace(source, 'import {FlatBindings} from "./FlatBindings.sol";',
                     'import {ERC20FlatBindings as FlatBindings} from "./ERC20FlatBindings.sol";')
    source = replace(source, 'import {FlatLineage} from "./FlatLineage.sol";',
                     'import {ERC20FlatLineage as FlatLineage} from "./ERC20FlatLineage.sol";')
    source = replace(source, "abstract contract FlatOrdinary", "abstract contract ERC20FlatOrdinary")
    source = replace(source, "        FlatOrdinary(lineage, lineageHash)",
                     "        ERC20FlatOrdinary(lineage, lineageHash)")
    return replace(source, "contract NativeBridgeVerifier11 is FlatOrdinary",
                   "contract ERC20BridgeVerifier is ERC20FlatOrdinary")


def recovery(source):
    source = variant_imports(source)
    source = replace(source, 'import {FlatLineage} from "./FlatLineage.sol";',
                     'import {ERC20FlatLineage as FlatLineage} from "./ERC20FlatLineage.sol";')
    source = replace(source, 'import {FlatBindings} from "./FlatBindings.sol";',
                     'import {FlatBindings} from "../../verifier/flat/FlatBindings.sol";\n'
                     'import {ERC20Context, IERC20ActivationContext} from "../ERC20Context.sol";')
    source = replace(source, 'import {NativeBridgeVerifier11} from "./NativeBridgeVerifier11.sol";',
                     'import {ERC20BridgeVerifier} from "./ERC20BridgeVerifier.sol";\n'
                     'import {INativeBridgeRecovery11} from "../../verifier/flat/NativeBridgeRecovery11.sol";')
    source = between(source, "interface INativeBridgeRecovery11", "abstract contract FlatRecovery")
    source = source.replace("FlatRecovery", "ERC20FlatRecovery").replace(
        "NativeBridgeVerifier11", "ERC20BridgeVerifier")
    source = replace(source, "    bytes32 private immutable _COIN;", "    bytes32 private immutable _COIN;\n"
                     "    address private immutable _TOKEN;\n    bytes32 private immutable _ASSET;")
    source = replace(source, "        _COIN = cfg.coin;", "        _COIN = cfg.coin;\n"
                     "        _TOKEN = cfg.token;\n        _ASSET = cfg.asset;")
    source = replace(source, "v.asset != FlatHash.ASSET", "v.asset != _ASSET")
    source = replace(source, "_shard(), VAULT, _TYPE, _COIN", "_shard(), VAULT, _TYPE, _COIN, _TOKEN, _ASSET")
    source = replace(source, "contract NativeBridgeRecovery11 is ERC20FlatRecovery",
                     "abstract contract ERC20RecoveryBinding is ERC20FlatRecovery")
    return source + """
abstract contract ERC20RecoveryActivation is ERC20RecoveryBinding {
    constructor(ERC20Context.Recovery memory ctx)
        ERC20RecoveryBinding(
            ctx.gamma, ERC20BridgeVerifier(ctx.ordinary), ctx.generation, ctx.release, ctx.pins
        )
    {}
}

/// @notice Fixed CREATE2 initcode. Only the activation context supplies the release arguments.
contract ERC20BridgeRecovery is ERC20RecoveryActivation {
    constructor() ERC20RecoveryActivation(IERC20ActivationContext(msg.sender).recoveryContext()) {}
}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    variants = [
        (ROOT / "NB2VaultBase.sol", "ERC20VaultBase.sol", base),
        (ROOT / "NB2VaultRecovered.sol", "ERC20VaultRecovered.sol", recovered),
        (FLAT / "FlatBindings.sol", "ERC20FlatBindings.sol", bindings),
        (FLAT / "FlatLineage.sol", "ERC20FlatLineage.sol", lineage),
        (FLAT / "NativeBridgeVerifier11.sol", "ERC20BridgeVerifier.sol", ordinary),
        (FLAT / "NativeBridgeRecovery11.sol", "ERC20BridgeRecovery.sol", recovery),
    ]
    OUT.mkdir(exist_ok=True)
    for original, name, transform in variants:
        target = OUT / name
        result = transform(original.read_text())
        content = replace(
            result, "pragma solidity", HEADER.format(name=original.name) + "pragma solidity"
        )
        content = subprocess.run(
            ["forge", "fmt", "--raw", "--root", str(ROOT.parents[1]), "-"],
            input=content,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        if check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f"regenerate {target}")
        else:
            target.write_text(content)


if __name__ == "__main__":
    main()
