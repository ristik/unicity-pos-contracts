#!/usr/bin/env python3
"""NB2-02 (bft-core#1098) bake-off: generate the candidate vaults and the bench test wrappers.

Each vault is one recent-buffer layout (tags | sparse) x one segment commitment (gap | mp | radix |
raw) x one parameter form: "imm" takes K and B as constructor immutables, "cK_B" fixes them as
compile-time constants. Output: src/gen/*.sol and test/gen/*.t.sol (both ignored by git).

    python3 gen.py
"""
import os
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
T = HERE / "templates"

LAYOUTS = ["tags", "sparse"]
COMMITS = {
    "gap": "circular-gap tree",
    "mp": "sorted-leaf adjacent multiproof",
    "radix": "compressed radix (crit-bit) tree",
    "raw": "raw flat segment (control)",
}
COMMIT_ID = {"gap": 0, "mp": 1, "radix": 2, "raw": 3}
KS = [32, 64, 128]
BS = [8, 16, 32]


def log2(x):
    return x.bit_length() - 1


def params_const(k, b):
    lb = log2(b)
    tpw = 256 // lb
    tw = (k + tpw - 1) // tpw
    decl = "\n".join(
        f"    uint256 internal constant {n} = {v};"
        for n, v in [("K", k), ("LOGK", log2(k)), ("B", b), ("LOGB", lb), ("TPW", tpw), ("TW", tw)]
    )
    init = "        if (k != K || b != B) revert BadConfig(17);"
    return decl, init


def params_imm():
    decl = "\n".join(
        f"    uint256 internal immutable {n};" for n in ["K", "LOGK", "B", "LOGB", "TPW", "TW"]
    )
    init = """        if (k < 2 || k > 128 || k & (k - 1) != 0) revert BadConfig(17);
        if (b < 2 || b > k || b > 32 || b & (b - 1) != 0) revert BadConfig(18);
        uint256 lk = 0;
        while ((1 << lk) < k) lk++;
        uint256 lb = 0;
        while ((1 << lb) < b) lb++;
        uint256 tpw = 256 / lb;
        K = k;
        LOGK = lk;
        B = b;
        LOGB = lb;
        TPW = tpw;
        TW = (k + tpw - 1) / tpw;"""
    return decl, init


def name(layout, commit, form):
    return f"V_{layout}_{commit}_{form}"


def render(layout, commit, form, k=None, b=None):
    decl, init = params_imm() if form == "imm" else params_const(k, b)
    src = (T / f"vault_{layout}.sol.in").read_text()
    src = src.replace("@PARAMS@", decl)
    src = src.replace("@PARAMS_INIT@", init)
    src = src.replace("@COMMON@", (T / "common.sol.in").read_text().rstrip("\n"))
    src = src.replace("@CTOR_COMMON@", (T / "ctor_common.sol.in").read_text().rstrip("\n"))
    src = src.replace("@COMMIT@", (T / f"commit_{commit}.sol.in").read_text().rstrip("\n"))
    src = src.replace("@COMMIT_NAME@", COMMITS[commit])
    src = src.replace("@NAME@", name(layout, commit, form))
    src = src.replace("@VARIANT@", f"{layout}, {commit}, {form}")
    return src


def main():
    sd = HERE / "src" / "gen"
    td = HERE / "test" / "gen"
    sd.mkdir(parents=True, exist_ok=True)
    td.mkdir(parents=True, exist_ok=True)
    for d in (sd, td):
        for f in d.glob("*.sol"):
            f.unlink()

    vaults = []  # (artifact, layout, commit, form, k|None, b|None)
    for layout in LAYOUTS:
        for commit in COMMITS:
            vaults.append((name(layout, commit, "imm"), layout, commit, "imm", None, None))
    for k in KS:
        for b in BS:
            form = f"c{k}_{b}"
            vaults.append((name("tags", "gap", form), "tags", "gap", form, k, b))
    for art, layout, commit, form, k, b in vaults:
        (sd / f"{art}.sol").write_text(render(layout, commit, form, k, b))

    # Test wrappers: one function per run so forge runs them in parallel and each writes its own CSV.
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// GENERATED by bench/nb2/gen.py. Do not edit.",
        "pragma solidity 0.8.37;",
        "",
        'import {BenchBase} from "../BenchBase.sol";',
        "",
    ]

    def cfg(art, layout, commit, form, k, b):
        lay = 0 if layout == "tags" else 1
        imm = "true" if form == "imm" else "false"
        return f'Cfg("{art}", {k}, {b}, {lay}, {COMMIT_ID[commit]}, {imm}, "{layout}", "{commit}", "{form}")'

    groups = {}

    def add(group, fn, body):
        groups.setdefault(group, []).append(f"    function test_{fn}() public {{\n        {body};\n    }}\n")

    dists = [(0, "uni"), (1, "conc"), (2, "desc"), (3, "adv")]
    # Recent buffer and settlement: both layouts, every (K, B), gap commitment, immutables.
    for layout in LAYOUTS:
        for k in KS:
            for b in BS:
                for di, dn in dists:
                    c = cfg(name(layout, "gap", "imm"), layout, "gap", "imm", k, b)
                    add(f"Recent_{layout}", f"recent_{layout}_K{k}_B{b}_{dn}", f"runRecent({c}, {di})")
    # Immutables against constants: tags/gap at every (K, B), uniform and concentrated.
    for k in KS:
        for b in BS:
            for di, dn in dists[:2]:
                form = f"c{k}_{b}"
                c = cfg(name("tags", "gap", form), "tags", "gap", form, k, b)
                add("Recent_const", f"recent_const_K{k}_B{b}_{dn}", f"runRecent({c}, {di})")
    # History replay: every commitment and K at B = 16 (the fold does not read B); constants too.
    for commit in COMMITS:
        for k in KS:
            c = cfg(name("tags", commit, "imm"), "tags", commit, "imm", k, 16)
            add("History", f"history_{commit}_K{k}", f"runHistory({c}, 0)")
            add("History", f"history_{commit}_K{k}_bucket", f"runHistory({c}, 1)")
    for k in KS:
        form = f"c{k}_16"
        c = cfg(name("tags", "gap", form), "tags", "gap", form, k, 16)
        add("History", f"history_const_K{k}", f"runHistory({c}, 0)")
    # Sealing per commitment (tags, B = 16) and per layout: uniform, concentrated, descending.
    for layout in LAYOUTS:
        for commit in COMMITS:
            for k in KS:
                for di, dn in dists:
                    c = cfg(name(layout, commit, "imm"), layout, commit, "imm", k, 16)
                    add(f"Seal_{layout}", f"seal_{layout}_{commit}_K{k}_{dn}", f"runSeal({c}, {di})")

    for group, fns in groups.items():
        lines.append(f"contract Bench_{group} is BenchBase {{")
        lines.extend(fns)
        lines.append("}")
        lines.append("")
    (td / "Bench.t.sol").write_text("\n".join(lines))
    print(f"{len(vaults)} vaults, {sum(len(v) for v in groups.values())} bench runs")


if __name__ == "__main__":
    main()
