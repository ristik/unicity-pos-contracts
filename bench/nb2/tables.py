#!/usr/bin/env python3
"""NB2-02 (bft-core#1098): turn the bench CSV rows into the Markdown result tables.

    python3 tables.py results 200 > RESULTS.md
"""
import csv
import json
import pathlib
import sys

COLS = ["group", "layout", "commit", "form", "K", "B", "dist", "phase", "endpoint", "m", "P",
        "gas", "cd", "cdgas", "refund", "hist"]
KS = [32, 64, 128]
BS = [8, 16, 32]
DIST = {0: "uniform", 1: "one bucket", 2: "one bucket, descending", 3: "one bucket, sort-adversarial"}
COMMITS = ["gap", "mp", "radix", "raw"]
CNAME = {"gap": "circular-gap tree", "mp": "sorted-leaf multiproof", "radix": "compressed radix",
         "raw": "raw flat (control)"}


def load(d):
    rows = []
    for f in sorted(pathlib.Path(d).glob("*.csv")):
        for r in csv.reader(open(f)):
            if len(r) != len(COLS):
                continue
            x = dict(zip(COLS, r))
            for k in ["K", "B", "dist", "m", "P", "gas", "cd", "cdgas", "refund", "hist"]:
                x[k] = int(x[k])
            rows.append(x)
    return rows


def pick(rows, **kw):
    out = [r for r in rows if all(r[k] == v for k, v in kw.items())]
    return out


def one(rows, **kw):
    out = pick(rows, **kw)
    if len(out) != 1:
        raise SystemExit(f"expected one row for {kw}, got {len(out)}")
    return out[0]


def g(rows, **kw):
    """The gas of a cell: the mean of its rows (uniform cells hold 16 samples), rounded."""
    out = pick(rows, **kw)
    return round(sum(r["gas"] for r in out) / len(out)) if out else None


def fmt(v):
    return "" if v is None else f"{v:,}"


def table(head, body):
    s = "| " + " | ".join(head) + " |\n"
    s += "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|\n"
    for r in body:
        s += "| " + " | ".join(str(c) for c in r) + " |\n"
    return s


def sizes(out_dir):
    res = {}
    for f in pathlib.Path(out_dir).glob("V_*.sol/V_*.json"):
        j = json.load(open(f))
        code = j.get("deployedBytecode", {}).get("object", "")
        res[f.stem] = (len(code) - 2) // 2 if code.startswith("0x") else len(code) // 2
    return res


def main():
    d = sys.argv[1]
    runs = sys.argv[2] if len(sys.argv) > 2 else "200"
    rows = load(d)
    tool = (pathlib.Path(d) / "toolchain.txt").read_text().strip() if (pathlib.Path(d) / "toolchain.txt").exists() else "forge"
    sz = sizes(pathlib.Path(d).parent / "out")
    refunds = sum(r["refund"] for r in rows)
    o = []
    o.append(f"# NB2-02 gas bake-off: measured tables (optimizer_runs = {runs})\n")
    o.append(
        f"Generated by `bench/nb2/run.sh` ({tool}; solc 0.8.37, via-IR, optimizer on, `optimizer_runs = {runs}`, "
        "EVM Cancun, `bytecode_hash = none`, no CBOR metadata). Every figure is the gas of one whole transaction "
        "(21,000 base and calldata included) run in isolation, so every account and slot it touches is cold, as a "
        "wallet's transaction meets them. The token verifier is a mock that returns the claimed verdict "
        "(192-byte evidence); real token evidence and verification (NB2-05, #1101) come on top. The recipient is an "
        f"existing EOA. Refunds over all rows: {refunds}.\n"
    )
    o.append("Workload words: *occupancy* m is the current buffer's population before the call; the call at "
             "m = K-1 is the sealing transaction. *previous* means the claim's endpoint is e = c - 1, so both "
             "buffers are scanned. *one bucket*: every identifier of both buffers and the claimed one share one "
             "bucket (ground identifiers), so the scan reads every live identifier. *steady*: segment 2 and later, "
             "every slot already nonzero; *gen0*/*gen1*: segments 0 and 1, the first writes of each buffer.\n")

    rec = [r for r in rows if r["group"] == "recent"]

    # ---------------------------------------------------------------- recent buffers, steady
    for lay in ["tags", "sparse"]:
        o.append(f"\n## Recent buffers and settlement, P = 0, `{lay}` layout, steady state\n")
        o.append("Circular-gap commitment, K and B as immutables.\n")
        head = ["K", "B", "uni cur m=0", "uni cur m=1", "uni cur m=K/2", "uni cur m=K-2", "uni prev m=0",
                "uni prev m=K/2", "uni prev m=K-2", "bucket cur m=K/2", "bucket cur m=K-2",
                "bucket prev m=K-2"]
        body = []
        for k in KS:
            for b in BS:
                q = dict(layout=lay, commit="gap", form="imm", K=k, B=b, phase="steady")
                body.append([k, b] + [fmt(g(rec, dist=0, endpoint="current", m=m, **q)) for m in [0, 1, k // 2, k - 2]]
                            + [fmt(g(rec, dist=0, endpoint="previous", m=m, **q)) for m in [0, k // 2, k - 2]]
                            + [fmt(g(rec, dist=1, endpoint="current", m=m, **q)) for m in [k // 2, k - 2]]
                            + [fmt(g(rec, dist=1, endpoint="previous", m=k - 2, **q))])
        o.append(table(head, body))

    # ---------------------------------------------------------------- sealing and the reserve
    o.append("\n## The sealing transaction and the wallet reserve (steady state, circular-gap, immutables)\n")
    o.append("*seal* is the call at m = K-1, current endpoint, for uniform identifiers and for one bucket in "
             "random, descending and sort-adversarial arrival order (descending 8-chunks, perfectly "
             "interleaved merges). *surcharge* is the uniform seal minus the uniform call at m = K-2 (the seal "
             "reads K-1 cold identifiers itself). *scan* is the previous-endpoint call at m = K-2 with every "
             "identifier in the claimed bucket (2K-2 identifier reads) minus the cheapest call. *worst* is the "
             "most expensive measured call: previous endpoint, m = K-1, one bucket, so 2K-1 cold identifier "
             "reads and then a seal sorting one bucket of K. *envelope* is worst minus cheapest (the cheapest "
             "sample: uniform, current, m = 0): what a wallet must add to a simulated gas figure, because "
             "intervening payments can move a call from the cheapest state to the worst.\n")
    head = ["layout", "K", "B", "seal uni", "seal bucket", "seal desc", "seal adv", "surcharge", "scan",
            "worst", "cheapest", "envelope"]
    body = []
    env = {}
    for lay in ["tags", "sparse"]:
        for k in KS:
            for b in BS:
                q = dict(layout=lay, commit="gap", form="imm", K=k, B=b, phase="steady")
                seals = [g(rec, dist=d, endpoint="current", m=k - 1, **q) for d in [0, 1, 2, 3]]
                pu = g(rec, dist=0, endpoint="current", m=k - 2, **q)
                allp = [r["gas"] for r in pick(rec, **q)]
                cheap = min(allp)
                worst = max(allp)
                scan = g(rec, dist=1, endpoint="previous", m=k - 2, **q) - cheap
                env[(lay, k, b)] = worst - cheap
                body.append([lay, k, b] + [fmt(x) for x in seals]
                            + [fmt(seals[0] - pu), fmt(scan), fmt(worst), fmt(cheap), fmt(worst - cheap)])
    o.append(table(head, body))
    o.append("\nThe envelope over every phase, including the first-generation segments 0 and 1 (their "
             "cheapest call is the first write of a buffer, and segment 1's worst seal writes a zero head "
             "slot), measured against the steady cheapest call:\n")
    head = ["layout", "K", "B", "worst gen0", "worst gen1", "worst steady", "max - steady cheapest"]
    body = []
    for lay in ["tags", "sparse"]:
        for k in KS:
            for b in BS:
                q = dict(layout=lay, commit="gap", form="imm", K=k, B=b)
                w = [max(r["gas"] for r in pick(rec, phase=ph, **q)) for ph in ["gen0", "gen1", "steady"]]
                cheap = min(r["gas"] for r in pick(rec, phase="steady", **q))
                body.append([lay, k, b] + [fmt(x) for x in w] + [fmt(max(w) - cheap)])
    o.append(table(head, body))

    # ---------------------------------------------------------------- first generation
    o.append("\n## First-generation storage (segments 0 and 1), current endpoint, uniform\n")
    head = ["layout", "K", "B", "gen0 m=0", "gen0 m=1", "gen0 m=K/2", "gen0 seal", "gen1 m=0", "gen1 m=K/2",
            "gen1 seal", "steady m=0", "steady m=K/2", "steady seal"]
    body = []
    for lay in ["tags", "sparse"]:
        for k in KS:
            for b in [16]:
                q = dict(layout=lay, commit="gap", form="imm", K=k, B=b, dist=0, endpoint="current")
                body.append([lay, k, b] + [fmt(g(rec, phase="gen0", m=m, **q)) for m in [0, 1, k // 2, k - 1]]
                            + [fmt(g(rec, phase="gen1", m=m, **q)) for m in [0, k // 2, k - 1]]
                            + [fmt(g(rec, phase="steady", m=m, **q)) for m in [0, k // 2, k - 1]])
    o.append(table(head, body))

    # ---------------------------------------------------------------- deposit
    o.append("\n## Deposit\n")
    head = ["layout", "first deposit (A zero to nonzero)", "steady deposit", "calldata bytes"]
    body = []
    for lay in ["tags", "sparse"]:
        r1 = pick(rows, group="recent", layout=lay, commit="gap", form="imm", K=64, B=16, dist=0, phase="deposit-first")[0]
        r2 = pick(rows, group="recent", layout=lay, commit="gap", form="imm", K=64, B=16, dist=0, phase="deposit-steady")[0]
        body.append([lay, fmt(r1["gas"]), fmt(r2["gas"]), r1["cd"]])
    o.append(table(head, body))

    # ---------------------------------------------------------------- history
    hist = [r for r in rows if r["group"] == "history"]
    o.append("\n## Historical segments: replay cost by commitment (tags, B = 16, steady, m = K/2, current endpoint)\n")
    o.append("Gas of the whole transaction and its calldata bytes (mock evidence included). The P segments "
             "hold uniform identifiers. *per segment* is (G(100) - G(10)) / 90 and the mean proof bytes.\n")
    head = ["commitment", "K", "P=0", "P=1", "P=10", "P=100", "calldata P=0", "P=1", "P=10", "P=100",
            "per segment gas", "per segment bytes"]
    body = []
    for c in COMMITS:
        for k in KS:
            q = dict(layout="tags", commit=c, form="imm", K=k, endpoint="current", phase="steady", dist=0)
            gs = [g(hist, P=p, **q) for p in [0, 1, 10, 100]]
            cds = [one(hist, P=p, **q)["cd"] for p in [0, 1, 10, 100]]
            h100 = one(hist, P=100, **q)["hist"]
            body.append([CNAME[c], k] + [fmt(x) for x in gs] + [fmt(x) for x in cds]
                        + [fmt(round((gs[3] - gs[2]) / 90)), f"{(h100 - 32) / 100:.1f}"])
    o.append(table(head, body))

    o.append("\n### Previous endpoint and one-bucket segments\n")
    o.append("The same replay with the claim's endpoint at e = c - 1 (both buffers scanned), and with every "
             "identifier of the P segments in one bucket (the claimed identifier is uniform).\n")
    head = ["commitment", "K", "prev P=0", "prev P=10", "prev P=100", "bucket P=10", "bucket P=100",
            "bucket per segment gas", "bucket per segment bytes"]
    body = []
    for c in COMMITS:
        for k in KS:
            q = dict(layout="tags", commit=c, form="imm", K=k, phase="steady")
            pv = [g(hist, P=p, endpoint="previous", dist=0, **q) for p in [0, 10, 100]]
            bk = [g(hist, P=p, endpoint="current", dist=1, **q) for p in [10, 100]]
            hb = one(hist, P=100, endpoint="current", dist=1, **q)["hist"]
            body.append([CNAME[c], k] + [fmt(x) for x in pv] + [fmt(x) for x in bk]
                        + [fmt(round((bk[1] - bk[0]) / 90)), f"{(hb - 32) / 100:.1f}"])
    o.append(table(head, body))

    o.append("\n### Replay per intervening payment\n")
    o.append("A claim waiting through N payments carries about N/K segment proofs: the marginal replay gas and "
             "calldata per intervening payment are the per-segment figures divided by K.\n")
    head = ["commitment", "K", "gas per payment", "bytes per payment"]
    body = []
    for c in COMMITS:
        for k in KS:
            q = dict(layout="tags", commit=c, form="imm", K=k, endpoint="current", phase="steady", dist=0)
            gs = (g(hist, P=100, **q) - g(hist, P=10, **q)) / 90
            h100 = one(hist, P=100, **q)["hist"]
            body.append([CNAME[c], k, f"{gs / k:.0f}", f"{(h100 - 32) / 100 / k:.2f}"])
    o.append(table(head, body))

    # ---------------------------------------------------------------- seal by commitment
    seal = [r for r in rows if r["group"] == "seal"]
    o.append("\n## Sealing by commitment and layout (steady, B = 16, current endpoint)\n")
    o.append("*pre* is the call at m = K-2, *seal* the call at m = K-1; surcharge = seal - pre, per arrival "
             "distribution.\n")
    head = ["layout", "commitment", "K", "pre uni", "seal uni", "surcharge uni", "surcharge bucket",
            "surcharge desc", "surcharge adv"]
    body = []
    for lay in ["tags", "sparse"]:
        for c in COMMITS:
            for k in KS:
                q = dict(layout=lay, commit=c, form="imm", K=k)
                vals = []
                for dist in [0, 1, 2, 3]:
                    pre = g(seal, phase="preseal", dist=dist, **q)
                    s = g(seal, phase="seal", dist=dist, **q)
                    vals.append((pre, s))
                body.append([lay, CNAME[c], k, fmt(vals[0][0]), fmt(vals[0][1])]
                            + [fmt(s - pre) for pre, s in vals])
    o.append(table(head, body))

    # ---------------------------------------------------------------- immutables vs constants
    o.append("\n## Immutables against compile-time constants (tags, circular-gap)\n")
    o.append("Gas with K and B as constructor immutables minus the same vault with them as constants "
             "(positive: immutables cost more). Runtime code size in bytes.\n")
    rc = [r for r in rows if r["group"] in ("recent",)]
    head = ["K", "B", "cur m=K/2 uni", "prev m=K/2 uni", "prev m=K-2 bucket", "seal uni", "seal bucket",
            "history P=10", "history P=100", "code imm", "code const"]
    body = []
    for k in KS:
        for b in BS:
            def dlt(**kw):
                a = g(rc, form="imm", layout="tags", commit="gap", K=k, B=b, phase="steady", **kw)
                cst = g(rc, form=f"c{k}_{b}", layout="tags", commit="gap", K=k, B=b, phase="steady", **kw)
                return None if a is None or cst is None else a - cst
            hp = []
            for p in [10, 100]:
                if b == 16:
                    a = g(hist, form="imm", commit="gap", K=k, P=p, dist=0, endpoint="current")
                    cst = g(hist, form=f"c{k}_16", commit="gap", K=k, P=p, dist=0, endpoint="current")
                    hp.append(fmt(a - cst))
                else:
                    hp.append("")
            body.append([k, b, fmt(dlt(dist=0, endpoint="current", m=k // 2)),
                         fmt(dlt(dist=0, endpoint="previous", m=k // 2)),
                         fmt(dlt(dist=1, endpoint="previous", m=k - 2)),
                         fmt(dlt(dist=0, endpoint="current", m=k - 1)),
                         fmt(dlt(dist=1, endpoint="current", m=k - 1))] + hp
                        + [fmt(sz.get("V_tags_gap_imm")), fmt(sz.get(f"V_tags_gap_c{k}_{b}"))])
    o.append(table(head, body))

    o.append("\n## Runtime code size of the immutable-parameter candidates (bytes)\n")
    head = ["layout"] + [CNAME[c] for c in COMMITS]
    body = [[lay] + [fmt(sz.get(f"V_{lay}_{c}_imm")) for c in COMMITS] for lay in ["tags", "sparse"]]
    o.append(table(head, body))
    print("\n".join(o))


if __name__ == "__main__":
    main()
